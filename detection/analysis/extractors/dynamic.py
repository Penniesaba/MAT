"""CEF (Common Event Format) log parser for eBPF monitor output.

This module provides parsing of CEF-formatted logs generated by the eBPF monitor
into RuntimeEventFact objects for security analysis.

CEF format: CEF:Version|Vendor|Product|Version|SigID|Name|Severity|Extensions
"""

from __future__ import annotations

import logging
import re
from typing import Mapping

from analysis.facts.ids import make_runtime_event_id
from analysis.facts.schema import RuntimeEventFact, RuntimeEventKind

logger = logging.getLogger(__name__)

# Event type to RuntimeEventKind mapping
EVENT_KIND_MAP: Mapping[str, RuntimeEventKind] = {
    "PROC_EXEC": RuntimeEventKind.PROCESS_EXEC,
    "FILE_OPEN": RuntimeEventKind.FILE_ACCESS,
    "FILE_READ": RuntimeEventKind.FILE_ACCESS,
    "FILE_WRITE": RuntimeEventKind.FILE_ACCESS,
    "FILE_UNLINK": RuntimeEventKind.FILE_ACCESS,
    "NET_CONNECT": RuntimeEventKind.NETWORK_CONNECT,
    "NET_SOCKET": RuntimeEventKind.NETWORK_CONNECT,
}

# File event types for command extraction from dst
FILE_EVENTS = {"FILE_OPEN", "FILE_READ", "FILE_WRITE", "FILE_UNLINK"}

# Process event types for dproc extraction
PROCESS_EVENTS = {"PROC_EXEC"}


def _parse_extensions(extension_str: str) -> dict[str, str]:
    """Parse CEF extension string into a dictionary.

    Args:
        extension_str: Space-separated key=value pairs. Values may contain
            spaces and are extracted until the next key=value pattern.

    Returns:
        Dictionary of extension key-value pairs.
    """
    extensions: dict[str, str] = {}

    # Match key=value where value extends to the next key=value or end of string.
    # Values may contain spaces. Negative lookahead (?!\s+\w+=) stops matching
    # when a space is followed by a key=value pattern.
    pattern = re.compile(r"(\w+)=([^\s]*(?:\s+(?!\w+=)[^\s]*)*)")

    for match in pattern.finditer(extension_str):
        key = match.group(1)
        value = match.group(2)
        extensions[key] = value

    return extensions


def _parse_cef_line(line: str) -> RuntimeEventFact | None:
    """Parse a single CEF log line into a RuntimeEventFact.

    Args:
        line: A single line of CEF-formatted log.

    Returns:
        RuntimeEventFact if parsing succeeds and event type is relevant,
        None otherwise.
    """
    stripped = line.strip()
    if not stripped.startswith("CEF:"):
        return None

    parts = stripped.split("|", 7)
    if len(parts) < 8:
        logger.debug("CEF line has fewer than 8 fields: %s", line)
        return None

    # parts[0] = "CEF:Version", parts[1] = Vendor, parts[2] = Product,
    # parts[3] = Version, parts[4] = SigID, parts[5] = Name,
    # parts[6] = Severity, parts[7] = Extensions
    sig_id = parts[4]
    extensions_str = parts[7]

    try:
        extensions = _parse_extensions(extensions_str)
    except Exception as e:
        logger.debug("Failed to parse extensions for line: %s, error: %s", line, e)
        return None

    # Check if event type is relevant
    if sig_id not in EVENT_KIND_MAP:
        return None

    event_kind = EVENT_KIND_MAP[sig_id]

    # Extract pid from spid
    pid: int | None = None
    spid = extensions.get("spid")
    if spid is not None:
        try:
            pid = int(spid)
        except ValueError:
            logger.debug("Failed to parse spid '%s' as int", spid)
            pid = None

    # Extract syscall from sproc
    syscall = extensions.get("sproc")

    # Extract command based on event type
    command: str | None = None
    if sig_id in PROCESS_EVENTS:
        command = extensions.get("dproc")
    elif sig_id in FILE_EVENTS:
        command = extensions.get("dst")

    # Extract timestamp from rt
    timestamp = extensions.get("rt")

    # Generate ID
    if pid is not None and syscall is not None:
        fact_id = make_runtime_event_id(syscall, pid)
    elif pid is not None:
        fact_id = make_runtime_event_id(sig_id.lower(), pid)
    else:
        fact_id = f"runtime:{sig_id.lower()}:unknown"

    return RuntimeEventFact(
        type="runtime",
        id=fact_id,
        file="dynamic",
        line=0,
        extractor="cef",
        kind=event_kind,
        syscall=syscall,
        command=command,
        pid=pid,
        container_id=None,
        timestamp=timestamp,
        correlated_entrypoint=None,
        correlated_sink=None,
        confidence=None,
    )


def parse_cef_logs(cef_text: str) -> list[RuntimeEventFact]:
    """Parse CEF-formatted log text into RuntimeEventFact objects.

    Args:
        cef_text: Multi-line CEF-formatted log text from eBPF monitor.

    Returns:
        List of RuntimeEventFact objects extracted from the CEF logs.
        Empty lines and lines with parse errors are silently skipped.
    """
    if not cef_text or not cef_text.strip():
        return []

    facts: list[RuntimeEventFact] = []

    for line in cef_text.splitlines():
        stripped = line.strip()
        if not stripped:
            continue

        try:
            fact = _parse_cef_line(stripped)
            if fact is not None:
                facts.append(fact)
        except Exception as e:
            logger.debug("Error parsing CEF line: %s, error: %s", line, e)
            continue

    return facts